import { Alert, Platform } from 'react-native';

/**
 * Demande de confirmation multiplateforme.
 * `Alert.alert` ne fait rien sur le web : on y utilise la boîte de dialogue du navigateur.
 */
export function confirmAction({
  title,
  message,
  confirmLabel,
  onConfirm,
}: {
  title: string;
  message?: string;
  confirmLabel: string;
  onConfirm: () => void;
}) {
  if (Platform.OS === 'web') {
    if (window.confirm(message ? `${title}\n\n${message}` : title)) onConfirm();
    return;
  }
  Alert.alert(title, message, [
    { text: 'Annuler', style: 'cancel' },
    { text: confirmLabel, style: 'destructive', onPress: onConfirm },
  ]);
}
